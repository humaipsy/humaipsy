//! Backend-agnostic chat-completion abstraction. `HumaiPsyAgent` (see `crate::agent`)
//! depends on `Provider`, not on any specific backend — today the only
//! implementation is [`ollama_provider::OllamaProvider`], which is a thin adapter
//! over the existing, unchanged `crate::ollama` module (its HTTP client, streaming
//! engine, and `HttpPolicy`/air-gap enforcement are untouched by this module).
//!
//! Adding a new backend (OpenAI, Anthropic, ...) later means writing a new
//! `impl Provider for SomeProvider` here and constructing it at the call site —
//! nothing in `agent.rs` or `apps/humaipsy` needs to branch on which backend is in
//! use. No such backend exists yet; this crate ships exactly one implementation.

pub mod ollama_provider;
pub mod token_budget;

use crate::ollama::{InferenceTimingSnapshot, OllamaStopEpoch, TokenUsage};
use crate::recording::timing::InferenceTraceContext;

/// Cooperative-cancellation handle, shared with the caller's UI so an
/// in-flight generation can be abandoned (the desktop app uses this when the
/// user starts a new run mid-generation). Reuses the existing epoch-counter
/// type from `crate::ollama` — its shape (an `Arc<AtomicU64>` plus a captured
/// value) isn't actually Ollama-specific, so it isn't renamed, just reused.
pub type StopEpoch = OllamaStopEpoch;

/// A single chat-completion request, backend-agnostic.
pub struct ChatRequest<'a> {
    /// May be empty — providers are expected to fall back to their own
    /// default model in that case (mirrors `crate::ollama`'s existing
    /// `DEFAULT_OLLAMA_MODEL` fallback behavior).
    pub model: &'a str,
    /// System/instruction prompt.
    pub instruction: &'a str,
    /// User-facing input (already-formatted memory context, as `agent.rs`
    /// builds it today).
    pub input: &'a str,
    /// Caps generated output length. This is the "professional cut" knob
    /// promoted to the trait level — every future provider takes the same
    /// field, instead of each one inventing its own generation-limit API.
    pub max_output_tokens: Option<u32>,
    pub stop_epoch: Option<StopEpoch>,
    /// Recording/tracing context (CSV `source` column, ledger event linkage) —
    /// required by `crate::recording::experiment_csv`'s call chain, not optional.
    pub trace_context: InferenceTraceContext,
}

/// The result of a chat-completion call.
pub struct ChatResponse {
    /// The model that actually served the request (a provider may resolve
    /// an empty/default `model` request field to a concrete name).
    pub model: String,
    pub text: String,
    pub usage: Option<TokenUsage>,
    pub timing: InferenceTimingSnapshot,
}

/// A backend capable of serving chat completions and listing its models.
// The `#[must_use]` that `async_trait` stamps on each boxed future is already implied by
// the future type itself, which is what `double_must_use` (new in clippy 1.99) objects
// to. The attribute is generated by the macro, so it cannot be removed here; the lint is
// about the macro's expansion rather than about this trait.
#[allow(clippy::double_must_use)]
#[async_trait::async_trait]
pub trait Provider: Send + Sync {
    /// Stable lowercase identifier (e.g. `"ollama"`) — for logging/diagnostics,
    /// not for branching UI logic on (that defeats the point of the trait).
    fn id(&self) -> &'static str;

    async fn chat(&self, request: ChatRequest<'_>) -> anyhow::Result<ChatResponse>;

    async fn list_models(&self) -> anyhow::Result<Vec<String>>;
}
